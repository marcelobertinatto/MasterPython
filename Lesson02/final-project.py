print("Welcome to the tip calculator!")
total_bill = float(input("What is the total bill? $ "))
total_tip = int(input("What percentage tip would you like to give? 10, 12, or 15? "))
num_people = int(input("How many people to split the bill? "))
total_bill = (total_bill / num_people) * (1 + total_tip / 100)
print(f"Total bill per person: {total_bill:.2f}")